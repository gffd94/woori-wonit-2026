// tab으로 선택, esc로 자동완성 취소

// 두 수를 더하는 함수
//함수 이름은 add야
// ② 인라인 채팅 - Ctrl + I (가장 많이 씁니다)
function add(a, b) {
    return a + b;
}

// ③ 채팅 패널 - Ctrl + Alt + I
// ④ 빠른 채팅 - Ctrl + Shift + Alt + L
// 두 수를 빼는 함수
function subtract(a, b) {
    return a - b;
}

